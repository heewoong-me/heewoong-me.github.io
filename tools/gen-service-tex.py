#!/usr/bin/env python3
"""Generate service.tex for the CV from content/data/service.yml (single source with the homepage)."""
import os, sys
import yaml

SITE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CV_DIR = os.environ.get("CV_DIR", os.path.expanduser("~/project/personal/heewoong-cv"))
OUT = os.path.join(CV_DIR, "service.tex")

def tex(s):
    return str(s).replace("&", r"\&").replace("%", r"\%").replace("#", r"\#").replace("_", r"\_")

def venues(items):
    parts = []
    for it in items:
        s = f"{tex(it['venue'])} ({', '.join(str(y) for y in it['years'])})"
        if it.get("note"):
            s += f", {tex(it['note'])}"
        parts.append(s)
    return "; ".join(parts)

d = yaml.safe_load(open(os.path.join(SITE, "content", "data", "service.yml")))
lines = ["% AUTO-GENERATED by tools/gen-service-tex.py from content/data/service.yml — edit the YAML, not this file.",
         r"\section{Academic Service}", r"    \begin{onecolentry}", r"        \begin{highlights}"]
if d.get("conferences"):
    lines.append(rf"            \item \textbf{{Conference Reviewer}}: {venues(d['conferences'])}")
if d.get("journals"):
    lines.append(rf"            \item \textbf{{Journal Reviewer}}: {venues(d['journals'])}")
for a in d.get("awards") or []:
    t = tex(a["text"])
    if ": " in t:  # bold the label before the colon, matching the reviewer lines
        label, rest = t.split(": ", 1)
        t = rf"\textbf{{{label}}}: {rest}"
    lines.append(rf"            \item \hrefNoIcon{{{a['url']}}}{{{t}}}" if a.get("url") else rf"            \item {t}")
lines += [r"        \end{highlights}", r"    \end{onecolentry}", ""]
new = "\n".join(lines)
old = open(OUT).read() if os.path.exists(OUT) else None
if old != new:
    open(OUT, "w").write(new)
    print(f"wrote {OUT}")
else:
    print(f"{OUT} unchanged")
